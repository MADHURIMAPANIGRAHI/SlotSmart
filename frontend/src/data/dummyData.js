// --- Helper function to transform the data structure ---
const transformTimetableForUI = (data) => {
    const daysOrder = ["monday", "tuesday", "wednesday", "thursday", "friday", "saturday"];
    const sections = ["A", "B", "C", "D"];
    const finalSchedule = {};

    daysOrder.forEach(day => {
        const capitalizedDay = day.charAt(0).toUpperCase() + day.slice(1);
        finalSchedule[capitalizedDay] = {};
        sections.forEach(section => {
            finalSchedule[capitalizedDay][section] = {};
        });

        const dayData = data.timetable[day];
        if (dayData) {
            dayData.forEach(timeEntry => {
                const time = timeEntry.time;
                Object.entries(timeEntry.schedule).forEach(([sectionKey, classData]) => {
                    const section = sectionKey.replace('section', '').toUpperCase();
                    if (finalSchedule[capitalizedDay][section]) {
                        finalSchedule[capitalizedDay][section][time] = classData;
                    }
                });
            });
        }
    });
    return finalSchedule;
};
const filterScheduleForTeacher = (masterSchedule, teacherName) => {
    const teacherSchedule = {};
    // Iterate over each time slot in the master schedule
    for (const [time, days] of Object.entries(masterSchedule)) {
        const filteredDays = {};
        // Iterate over each day within that time slot
        for (const [day, classData] of Object.entries(days)) {
            // If a class exists AND the teacher's name matches, keep it. Otherwise, set it to null.
            if (classData && classData.teacher === teacherName) {
                filteredDays[day] = classData;
            } else {
                filteredDays[day] = null;
            }
        }
        teacherSchedule[time] = filteredDays;
    }
    return teacherSchedule;
};

